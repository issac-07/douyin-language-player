import { expect, test, type Page } from '@playwright/test';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFile } from 'node:fs/promises';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

async function openLanguageVideo(page: Page, filename: string) {
  await page.goto('/');
  await page.getByLabel('Choose MP4 file').setInputFiles(path.join(root, 'data/fixtures', filename));
  await expect(page.getByRole('heading', { name: filename })).toBeVisible();
  await page.getByText('Subtitle analysis settings', { exact: true }).click();
  await page.getByLabel('OCR controls', {exact:true}).selectOption('advanced');
  await page.getByLabel('Samples / second').fill('2');
  const rerun = page.getByRole('button', { name: 'Scan OCR again', exact: true });
  if (await rerun.count()) await rerun.click();
  else await page.getByRole('button', { name: 'Create / open subtitles', exact: true }).click();
  await expect(page.getByTestId('analysis-status')).toHaveAttribute('data-status', 'completed', { timeout: 60_000 });
  await page.getByRole('slider', { name: 'Seek video' }).fill('1');
  await expect(page.getByTestId('subtitle-vietnamese')).toContainText('Hôm nay', { timeout: 45_000 });
  await page.getByText('Subtitle analysis settings', { exact: true }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
}

async function checkBounds(page: Page, above = true) {
  const bounds = (await page.getByTestId('subtitle-image-bounds').boundingBox())!;
  const overlay = (await page.getByTestId('interactive-overlay').boundingBox())!;
  expect(overlay.x).toBeGreaterThanOrEqual(bounds.x - 1);
  expect(overlay.y).toBeGreaterThanOrEqual(bounds.y - 1);
  expect(overlay.x + overlay.width).toBeLessThanOrEqual(bounds.x + bounds.width + 1);
  expect(overlay.y + overlay.height).toBeLessThanOrEqual(bounds.y + bounds.height + 1);
  if (above) expect(overlay.y + overlay.height).toBeLessThanOrEqual(bounds.y + bounds.height * .6 + 1);
  expect(await page.locator('.video-stage').getByTestId('interactive-overlay').count()).toBe(1);
}

